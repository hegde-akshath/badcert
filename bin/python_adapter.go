package main

import (
	"fmt"
	"os"
	"encoding/json"
    "text/template"
)

const pythonTemplate = `# AUTO-GENERATED BY GO - DO NOT EDIT
null = None
true = True
false = False
{{.VarName}} = {{.Content}}
`
type TemplateData struct {
	VarName string
	Content string
}

type PythonCertDataGenerator struct {
	DataStore map[string]*TestCertData
}

func NewPythonCertDataGenerator() *PythonCertDataGenerator {
	return &PythonCertDataGenerator{
		DataStore: make(map[string]*TestCertData),
	}
}

func (pg *PythonCertDataGenerator) AddTestCertData(testId string, testCertData *TestCertData) {
	pg.DataStore[testId] = testCertData
}

func (pg *PythonCertDataGenerator) WritePythonCertDataFile(varname string, pythonCertDataFilePath string) {
	var err error
	var jsonData []byte
    var f *os.File 

	f, err = os.Create(pythonCertDataFilePath)
	if err != nil {
		panic(err)
	}
	defer f.Close()

	jsonData, err = json.MarshalIndent(pg.DataStore, "", "    ")
	if err != nil {
		panic(err)
	}
    
	templateData := &TemplateData{VarName: varname, Content: string(jsonData)}

	tmpl := template.Must(template.New("python").Parse(pythonTemplate))
	tmpl.Execute(f, templateData)

	fmt.Println("Python Cert Data file created")
}
